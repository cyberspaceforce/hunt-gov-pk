/* ==========================================================================
   Hunt Gov Pk — Utilities & data access
   --------------------------------------------------------------------------
   Job data is REAL and comes from data/jobs.js, which is generated by
   scraper/fetch_jobs.py from the official recruitment websites.
   ========================================================================== */
(function (HN) {
  "use strict";

  const DAY = 86400000;
  const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

  function parseDate(iso) {
    if (!iso) return null;
    const p = iso.split("-").map(Number);
    return new Date(p[0], p[1] - 1, p[2]);
  }

  function startOfToday() {
    const d = new Date();
    d.setHours(0, 0, 0, 0);
    return d;
  }

  const CACHE_KEY = "huntgovpk.liveData.v1";

  function readCache() {
    try {
      const raw = window.localStorage.getItem(CACHE_KEY);
      return raw ? JSON.parse(raw) : null;
    } catch (e) { return null; }
  }

  const utils = {
    hasData: false,
    data: null,
    jobs: [],
    govJobs: [],
    healthJobs: [],
    ads: [],
    newDepartments: [],
    sources: [],

    /**
     * (Re)load a full payload {generatedAt, sources, jobs, advertisements, newDepartments}.
     * Called once at start-up and again whenever live data arrives from /api/source.
     */
    setData(raw) {
      utils.data = raw || null;
      utils.hasData = !!raw;
      utils.jobs = raw && Array.isArray(raw.jobs)
        ? raw.jobs.map(function (j) {
            return Object.assign({}, j, { adDateObj: parseDate(j.adDate), closingDateObj: parseDate(j.closingDate) });
          })
        : [];
      utils.ads = raw && Array.isArray(raw.advertisements)
        ? raw.advertisements.map(function (a) { return Object.assign({}, a, { dateObj: parseDate(a.date) }); })
        : [];
      utils.govJobs = utils.jobs.filter(function (j) { return (j.group || "government") === "government"; });
      utils.healthJobs = utils.jobs.filter(function (j) { return j.group === "healthcare"; });
      utils.sources = (raw && raw.sources) || [];
      // Recount the new-department watch list from the jobs/ads we actually have
      utils.newDepartments = ((raw && raw.newDepartments) || []).map(function (d) {
        return Object.assign({}, d, {
          jobs: utils.jobs.filter(function (j) { return j.newDepartment === d.name; }).length,
          ads: utils.ads.filter(function (a) { return a.newDepartment === d.name; }).length
        });
      });
    },

    /** Persist live data so the next visit opens with the newest jobs instantly. */
    saveCache(raw) {
      try { window.localStorage.setItem(CACHE_KEY, JSON.stringify(raw)); } catch (e) { /* quota / private mode */ }
    },

    job(id) { return utils.jobs.find(function (j) { return j.id === id; }); },

    escapeHtml(value) {
      return String(value == null ? "" : value)
        .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
    },

    formatDate(date) {
      if (!date) return "—";
      const d = new Date(date);
      return d.getDate() + " " + MONTHS[d.getMonth()] + " " + d.getFullYear();
    },

    formatDateTime(iso) {
      if (!iso) return "—";
      const d = new Date(iso);
      return utils.formatDate(d) + ", " + d.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
    },

    daysUntil(date) {
      if (!date) return null;
      const d = new Date(date);
      d.setHours(0, 0, 0, 0);
      return Math.round((d - startOfToday()) / DAY);
    },

    /** Status is always computed from today's date, so it stays correct. */
    getStatus(job) {
      const left = utils.daysUntil(job.closingDateObj);
      if (left === null) return { key: "open", label: "Open", daysLeft: null };
      if (left < 0) return { key: "closed", label: "Closed", daysLeft: left };
      if (left <= 7) return { key: "closing", label: "Closing soon", daysLeft: left };
      return { key: "open", label: "Open", daysLeft: left };
    },

    isNew(job) {
      const d = utils.daysUntil(job.adDateObj);
      return d !== null && d >= -3;
    },

    daysLeftText(daysLeft) {
      if (daysLeft === null) return "Deadline not stated";
      if (daysLeft < 0) return "Closed";
      if (daysLeft === 0) return "Closes today";
      if (daysLeft === 1) return "1 day left";
      return daysLeft + " days left";
    },

    urgencyClass(daysLeft) {
      if (daysLeft === null) return "is-ok";
      if (daysLeft < 0) return "is-closed";
      if (daysLeft <= 3) return "is-urgent";
      if (daysLeft <= 7) return "is-soon";
      return "is-ok";
    },

    /** "BS-17" -> 17 (used for sorting / filtering). */
    scaleNumber(job) {
      const m = /(\d+)/.exec(job.payScale || "");
      return m ? Number(m[1]) : 0;
    },

    relativeTime(iso) {
      if (!iso) return "unknown";
      const mins = Math.round((Date.now() - new Date(iso).getTime()) / 60000);
      if (mins < 1) return "just now";
      if (mins < 60) return mins + " min ago";
      const h = Math.floor(mins / 60);
      if (h < 24) return h + (h === 1 ? " hour ago" : " hours ago");
      const d = Math.floor(h / 24);
      return d + (d === 1 ? " day ago" : " days ago");
    },

    /** Hours since the scraper last ran. */
    dataAgeHours() {
      const d = utils.data;
      if (!d || !d.generatedAt) return Infinity;
      return (Date.now() - new Date(d.generatedAt).getTime()) / 3600000;
    },

    plural(n, word, pluralWord) { return n + " " + (n === 1 ? word : pluralWord || word + "s"); },

    orgColor(seed) {
      const palette = [
        ["#e8eefb", "#1d3a8a"], ["#e6f4f1", "#0f5e54"], ["#f3ecfb", "#6b21a8"], ["#fdf1e4", "#9a4a07"],
        ["#e9f1f8", "#1e4b75"], ["#fde9ee", "#9f1239"], ["#ecf6e9", "#2f6b1f"], ["#eef0f4", "#334155"]
      ];
      let h = 0;
      for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
      const p = palette[h % palette.length];
      return { bg: p[0], fg: p[1] };
    },

    /** Two-letter monogram from a department name. */
    monogram(name) {
      const stop = { of: 1, and: 1, the: 1, in: 1, "&": 1 };
      const words = String(name).replace(/\(.*?\)/g, "").split(/[\s,/]+/)
        .filter(function (w) { return w && !stop[w.toLowerCase()] && /[A-Za-z]/.test(w); });
      return ((words[0] || "?")[0] + (words[1] ? words[1][0] : "")).toUpperCase();
    },

    debounce(fn, wait) {
      let t;
      return function () {
        const args = arguments, ctx = this;
        clearTimeout(t);
        t = setTimeout(function () { fn.apply(ctx, args); }, wait);
      };
    },

    tokenize(q) { return String(q || "").toLowerCase().split(/\s+/).filter(Boolean); },

    /** Wrap query terms in <mark>. Input must already be HTML-escaped. */
    highlight(escaped, query) {
      const terms = utils.tokenize(query).filter(function (t) { return t.length > 1; });
      if (!terms.length) return escaped;
      const pattern = terms.map(function (t) {
        return utils.escapeHtml(t).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      }).join("|");
      return escaped.replace(new RegExp("(" + pattern + ")", "gi"), '<mark class="hl">$1</mark>');
    },

    /**
     * Turn official clause text like "i) ... ii) ... OR i) ..." into
     * [[clause, clause], [clause]] - one array per alternative.
     */
    splitClauses(text) {
      if (!text) return [];
      return String(text)
        .split(/\s+OR\s+(?=[ivx]+\)|\(?[a-z]\)|[A-Z])/)
        .map(function (block) {
          return block
            .split(/\s+(?=(?:[ivx]+\)|\([a-z]\))\s)/i)
            .map(function (s) { return s.trim(); })
            .filter(Boolean);
        })
        .filter(function (b) { return b.length; });
    },

    hasValue(v) { return v !== null && v !== undefined && v !== "" && v !== 0; },

    /**
     * Clean scraped detail items into readable sections.
     * Input:  ["## Heading", "item", "1.", "→", "Degree Name", "## Positions Available", "1", ...]
     * Output: { sections: [{ heading, items: [] }], facts: [[label, value]] }
     *  - strips bullets / arrows / list numbering
     *  - drops empty, symbol-only, number-only and form-label items
     *  - re-joins sentences that were split across lines
     *  - turns "Heading" + one short value into a label/value fact
     *  - removes duplicates and redundant "N Years of Education" lines
     *  - drops headings that end up with nothing under them
     */
    cleanDetails(raw) {
      const JUNK = /^(degree name|degree title|summary|select|n\/?a|nil|none|null|-|details|job details)$/i;
      const BULLET = /^(?:[•·▪◦●○■□➢➤►▶→⇒✓✔*\-–—]+|\(?\d{1,2}[.)]|\(?[a-h][.)]|\(?[ivx]{1,4}\))\s+/i;
      const CONNECTOR = /(?:[,/&(\-–]|\b(?:and|or|of|in|the|with|for|to|as|on|at|by|including|such as))$/i;
      const SKIP_FACTS = /^(salary|last applying date|last date|location|apply|summary)$/i;

      function norm(text) {
        let t = String(text || "").replace(/\s+/g, " ").trim();
        let prev;
        do { prev = t; t = t.replace(BULLET, "").trim(); } while (t !== prev);
        return t.replace(/^[•·→\-–]\s*/, "").trim();
      }
      function meaningful(t) { return /[A-Za-z]/.test(t) && !JUNK.test(t); }

      // 1. normalise + split into raw groups
      const groups = [];
      let cur = { heading: "", items: [] };
      groups.push(cur);
      (raw || []).forEach(function (line) {
        const isHeading = typeof line === "string" && line.indexOf("## ") === 0;
        const text = norm(isHeading ? line.slice(3) : line).replace(/:$/, "").trim();
        if (!text) return;
        // "## these patients including" - a lowercase "heading" is really a sentence continuation
        if (isHeading && /^[a-z]/.test(text)) {
          if (cur.items.length) cur.items[cur.items.length - 1] += " " + text + ":";
          else cur.items.push(text + ":");
          return;
        }
        if (isHeading) { cur = { heading: text, items: [] }; groups.push(cur); return; }
        cur.items.push(text);
      });

      const sections = [], facts = [];
      groups.forEach(function (g) {
        // 2. re-join fragments: "... routine management of" + "these patients"
        const merged = [];
        g.items.forEach(function (it) {
          const last = merged[merged.length - 1];
          if (last && (CONNECTOR.test(last) || /^[a-z(]/.test(it) && !/[.!?:;]$/.test(last))) {
            merged[merged.length - 1] = last + " " + it;
          } else {
            merged.push(it);
          }
        });

        // 3. label/value pairs -> facts
        if (g.heading && merged.length === 1 && merged[0].length <= 60 && !/[.]$/.test(merged[0])) {
          if (!SKIP_FACTS.test(g.heading) && (meaningful(merged[0]) || /^\d+$/.test(merged[0]))) {
            facts.push([g.heading, merged[0].replace(/,(?=\S)/g, ", ")]);
          }
          return;
        }

        // 4. drop junk, dedupe, remove redundant "16 Years of Education"
        const seen = {};
        const yearsInText = merged.join(" ").match(/\((\d{2}) years?\)/gi) || [];
        const items = merged.filter(function (it) {
          if (!meaningful(it)) return false;
          const key = it.toLowerCase().replace(/[^a-z0-9]/g, "");
          if (seen[key]) return false;
          seen[key] = true;
          const yrs = /^(\d{2}) years? of education$/i.exec(it);
          if (yrs && yearsInText.some(function (m) { return m.indexOf(yrs[1]) !== -1; })) return false;
          return true;
        });
        if (items.length) sections.push({ heading: g.heading, items: items });
      });
      return { sections: sections, facts: facts };
    },

    getParams() { return new URLSearchParams(window.location.search); },

    jobUrl(job) { return "job-details.html?id=" + encodeURIComponent(job.id); }
  };

  // Start-up data: the bundled snapshot (data/jobs.js), or the live data saved by a
  // previous visit if that is newer.
  (function initialData() {
    const snapshot = window.HN_DATA || null;
    const cached = readCache();
    const newer = cached && cached.generatedAt && (!snapshot || new Date(cached.generatedAt) > new Date(snapshot.generatedAt));
    utils.setData(newer ? cached : snapshot);
  })();

  HN.utils = utils;
})(window.HN = window.HN || {});
